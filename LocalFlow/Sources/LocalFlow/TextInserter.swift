import AppKit
import ApplicationServices
import Carbon.HIToolbox

/// Fügt Text an der Cursor-Position der aktiven App ein — immer über Zwischenablage + Cmd+V.
/// Der AX-Direkteinfüge-Pfad (kAXSelectedTextAttribute) wurde entfernt: Bei Browser-/Web-Feldern
/// (Google-Suchleiste, Chrome-Adressleiste, Electron-Apps) liefert er .success, fügt aber NICHTS
/// ein. Cmd+V funktioniert dagegen universell — genau wie bei Wispr Flow und VoiceInk.
enum TextInserter {

    static func insert(_ text: String) {
        guard !text.isEmpty else { return }
        if IsSecureEventInputEnabled() {
            Log.error("Secure Event Input aktiv (Passwortfeld?) — Einfügen könnte fehlschlagen")
        }
        pasteViaClipboard(text)
    }

    // MARK: - Pasteboard-Pfad

    typealias PasteboardSnapshot = [[NSPasteboard.PasteboardType: Data]]

    /// Snapshot VOR clearContents ziehen — NSPasteboardItems werden beim Clear invalidiert.
    static func snapshotPasteboard() -> PasteboardSnapshot {
        var snapshot: PasteboardSnapshot = []
        for item in NSPasteboard.general.pasteboardItems ?? [] {
            var copy: [NSPasteboard.PasteboardType: Data] = [:]
            for type in item.types {
                if let data = item.data(forType: type) { copy[type] = data }
            }
            if !copy.isEmpty { snapshot.append(copy) }
        }
        return snapshot
    }

    static func restorePasteboard(_ snapshot: PasteboardSnapshot) {
        guard !snapshot.isEmpty else { return }
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        var items: [NSPasteboardItem] = []
        for entry in snapshot {
            let item = NSPasteboardItem()
            for (type, data) in entry { item.setData(data, forType: type) }
            items.append(item)
        }
        pasteboard.writeObjects(items)
    }

    private static func writeTransient(_ text: String) {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()
        pasteboard.setString(text, forType: .string)
        // Clipboard-Manager sollen den Eintrag ignorieren:
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType"))
        pasteboard.setData(Data(), forType: NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType"))
    }

    private static func pasteViaClipboard(_ text: String) {
        let pasteboard = NSPasteboard.general
        let snapshot = snapshotPasteboard()
        writeTransient(text)
        let ourChangeCount = pasteboard.changeCount

        // Kurze Pause, damit langsame (Electron-)Apps das neue Pasteboard sehen, dann Cmd+V.
        DispatchQueue.main.asyncAfter(deadline: .now() + 0.10) {
            postCmdV()
            Log.info("Eingefügt via Cmd+V (\(text.count) Zeichen)")
            // Restore erst nach ≥0,25 s — und nur, wenn niemand das Pasteboard inzwischen beschrieben hat.
            DispatchQueue.main.asyncAfter(deadline: .now() + 0.35) {
                guard pasteboard.changeCount == ourChangeCount else { return }
                restorePasteboard(snapshot)
            }
        }
    }

    /// Berechtigungsfreier Selbsttest des Snapshot/Write/Restore-Zyklus (ohne Cmd+V).
    /// Liefert (erfolgreich, Details).
    static func clipboardSelfTest() -> (Bool, String) {
        let pasteboard = NSPasteboard.general
        let before = snapshotPasteboard()
        let beforeString = pasteboard.string(forType: .string)

        let marker = "LocalFlow-Selbsttest äöü€🚀 \(UUID().uuidString)"
        writeTransient(marker)
        guard pasteboard.string(forType: .string) == marker else {
            return (false, "Schreiben in die Zwischenablage fehlgeschlagen")
        }
        guard pasteboard.data(forType: NSPasteboard.PasteboardType("org.nspasteboard.TransientType")) != nil else {
            return (false, "Transient-Marker fehlt")
        }
        restorePasteboard(before)
        let afterString = pasteboard.string(forType: .string)
        if before.isEmpty {
            return (true, "OK (Zwischenablage war leer; Testtext geschrieben und gelesen)")
        }
        guard afterString == beforeString else {
            return (false, "Restore-Abweichung: vorher \(beforeString?.prefix(40) ?? "nil"), nachher \(afterString?.prefix(40) ?? "nil")")
        }
        return (true, "OK (\(before.count) Pasteboard-Item(s) mit allen Typen wiederhergestellt)")
    }

    private static func postCmdV() {
        let source = CGEventSource(stateID: .privateState)
        let vKey = CGKeyCode(KeyCodeResolver.vKeyCode)
        let events: [(CGKeyCode, Bool)] = [
            (CGKeyCode(kVK_Command), true), (vKey, true), (vKey, false), (CGKeyCode(kVK_Command), false),
        ]
        for (key, down) in events {
            guard let e = CGEvent(keyboardEventSource: source, virtualKey: key, keyDown: down) else { continue }
            if key == vKey { e.flags = .maskCommand }
            e.post(tap: .cghidEventTap)
            usleep(10_000)
        }
    }
}
